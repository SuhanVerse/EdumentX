import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const exactVersion = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-([\da-zA-Z.-]+))?(?:\+[\da-zA-Z.-]+)?$/;
const sortedEntries = value => Object.entries(value || {}).sort(([a], [b]) => a.localeCompare(b, 'en'));

function json(root, filename) {
  try { return JSON.parse(readFileSync(path.join(root, filename), 'utf8')); }
  catch { throw new Error(`Cannot read valid ${filename}. Restore the tracked manifest/lockfile first.`); }
}

// These repositories use exact, caret, or tilde direct registry declarations.
// Reject unsupported ranges instead of guessing what npm would resolve.
function satisfies(version, declaration) {
  if (version === declaration) return true;
  const range = declaration.match(/^([~^])(\d+)\.(\d+)\.(\d+)$/);
  const resolved = version.match(exactVersion);
  if (!range || !resolved || resolved[4]) return false;
  const lower = range.slice(2).map(Number);
  const actual = resolved.slice(1, 4).map(Number);
  const compare = (left, right) => {
    for (let i = 0; i < 3; i += 1) if (left[i] !== right[i]) return left[i] - right[i];
    return 0;
  };
  const upper = range[1] === '~' ? [lower[0], lower[1] + 1, 0]
    : lower[0] > 0 ? [lower[0] + 1, 0, 0]
      : lower[1] > 0 ? [0, lower[1] + 1, 0] : [0, 0, lower[2] + 1];
  return compare(actual, lower) >= 0 && compare(actual, upper) < 0;
}

function lockedDependencies(root, folder) {
  const prefix = folder ? `${folder}/` : '';
  const manifest = json(root, `${prefix}package.json`);
  const lock = json(root, `${prefix}package-lock.json`);
  if (![2, 3].includes(lock.lockfileVersion) || !lock.packages?.['']) throw new Error(`${prefix}package-lock.json needs npm lockfile version 2 or 3.`);
  const groups = {};
  for (const field of ['dependencies', 'devDependencies']) {
    const declared = sortedEntries(manifest[field]);
    if (JSON.stringify(declared) !== JSON.stringify(sortedEntries(lock.packages[''][field]))) {
      throw new Error(`${prefix}package.json and package-lock.json ${field} declarations differ. Update the lockfile intentionally.`);
    }
    groups[field] = declared.map(([name, spec]) => {
      const version = lock.packages[`node_modules/${name}`]?.version;
      if (typeof version !== 'string' || !exactVersion.test(version)) throw new Error(`${prefix}${name}: exact locked version missing or invalid.`);
      if (typeof spec !== 'string' || !satisfies(version, spec)) throw new Error(`${prefix}${name}: locked version does not satisfy its declaration (or declaration syntax is unsupported).`);
      return `${name}@${version}`;
    });
  }
  return { manifest, groups };
}

function contents(root) {
  const app = lockedDependencies(root, '');
  const functions = lockedDependencies(root, 'functions');
  let node;
  try { node = readFileSync(path.join(root, '.nvmrc'), 'utf8').trim(); }
  catch { throw new Error('Missing .nvmrc. Restore the tracked Node version.'); }
  if (!exactVersion.test(node) || !/^npm@\d+\.\d+\.\d+$/.test(app.manifest.packageManager || '')) throw new Error('Expected an exact .nvmrc and npm packageManager version.');
  const android = json(root, 'app.json').expo?.plugins?.find(item => Array.isArray(item) && item[0] === 'expo-build-properties')?.[1]?.android;
  if (!['compileSdkVersion', 'targetSdkVersion', 'minSdkVersion'].every(key => Number.isInteger(android?.[key]))) throw new Error('Missing Android SDK versions in app.json.');
  const lines = [
    'EdumentX Android: dependency and toolchain inventory',
    'Generated by npm run requirements:update; verify with npm run requirements:check.',
    'Edit package.json, package-lock.json, .nvmrc, and app.json; then regenerate.',
    '',
    'This is a valid, comments-only pip requirements file: there are no required',
    'third-party Python packages. Optional Python helper scripts use the standard library.',
    'pip install -r requirements.txt installs nothing and does NOT set up the app.',
    'Use npm ci for the app and npm --prefix functions ci for the optional backend.',
    'Both package-lock.json files are authoritative, including every transitive version.',
    '',
    'Toolchains',
    `Preferred Node.js: ${node} (.nvmrc); supported: ${app.manifest.engines?.node}.`,
    `Preferred npm: ${app.manifest.packageManager.slice(4)} (packageManager); supported: ${app.manifest.engines?.npm}.`,
    `Cloud Functions deployed runtime: Node.js ${functions.manifest.engines?.node}; separate from the host app toolchain.`,
    'Android: JDK 21 recommended; Android Studio SDK Manager and Platform-Tools.',
    `Android SDK platform ${android.compileSdkVersion}; target ${android.targetSdkVersion}; minimum device API ${android.minSdkVersion} (app.json).`,
    ...(app.groups.dependencies.includes('react-native@0.81.5') ? [
      'React Native 0.81.5 build baseline: Gradle 8.14.3, Build-Tools 36.0.0,',
      'NDK 27.1.12297006; the locked React Native Gradle catalog selects native versions.',
    ] : ['Native versions: consult the locked React Native Gradle catalog and generated Gradle wrapper.']),
    'npm run setup:check -- --android verifies local native prerequisites after npm ci.',
    '',
    'Environment and platform setup',
    'Read README.md and Documentation/03-Implementation-Guides/PROJECT_SETUP.md.',
    'Copy .env.example once, supply your own public client settings, and register',
    'the Android package in Firebase to obtain google-services.json; never commit private credentials.',
    'Native Firebase requires a development build; Expo Go does not run this app.',
    'Native Swift iOS app and its separate toolchain: https://github.com/SuhanVerse/EdumentX-iOS',
  ];
  for (const [label, project] of [['App', app], ['Cloud Functions', functions]]) {
    for (const [field, title] of [['dependencies', 'direct dependencies'], ['devDependencies', 'direct development dependencies']]) {
      lines.push('', `${label}: ${title} (exact locked versions)`, ...project.groups[field]);
    }
  }
  return `${lines.map(line => line ? `# ${line}` : '#').join('\n')}\n`;
}

/** Generate from tracked public metadata only: no installs, subprocesses, or environment reads. */
export function syncRequirements({ root = repository, check = false } = {}) {
  const expected = contents(root);
  const destination = path.join(root, 'requirements.txt');
  let current;
  try { current = readFileSync(destination, 'utf8'); } catch { current = null; }
  const unchanged = current === expected;
  if (!check && !unchanged) writeFileSync(destination, expected);
  return { ok: !check || unchanged, updated: !check && !unchanged };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.slice(2).some(argument => argument !== '--check')) throw new Error('Usage: node scripts/syncRequirements.mjs [--check]');
    const result = syncRequirements({ check: process.argv.includes('--check') });
    console.log(result.ok ? 'requirements.txt matches the locked dependencies.' : 'requirements.txt is stale or missing; run npm run requirements:update.');
    process.exitCode = result.ok ? 0 : 1;
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
